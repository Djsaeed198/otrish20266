/**
 * Returns SEO metadata for a given activeSegment, guaranteed with tailored FAQs,
 * spelling variant expansions, and Schema.org mappings.
 */
export function getSeoForSegment(segment: string): PageSeoItem {
  let item: PageSeoItem;

  if (SEO_CATALOG[segment]) {
    item = { ...SEO_CATALOG[segment] };
  } else {
    // Check aliases
    const aliasMap: Record<string, string> = {
      "appointment": "ma35",
      "appointments": "ma35",
      "arbeitnehmerveranlagung": "tax-return",
      "id-austria": "id-austria-guide",
      "wohnen": "housesearch",
      "staatsbuergerschaft": "citizenship",
      "rwr": "rwr-calculator"
    };

    if (aliasMap[segment] && SEO_CATALOG[aliasMap[segment]]) {
      item = { ...SEO_CATALOG[aliasMap[segment]] };
    } else {
      item = {
        id: segment,
        path: `/${segment}`,
        title: `راهنما و خدمات ${segment} در اتریش | اتریش‌نشین`,
        h1: `راهنما و اطلاعات تخصصی ${segment} در اتریش ۲۰۲۶`,
        description: `مرجع جامع، قوانین و راهنمای کاربردی بخش ${segment} ویژه فارسی‌زبانان مقیم اتریش. دسترسی سریع و رایگان در سوپراپلیکیشن اتریش‌نشین.`,
        keywords: `${segment}, اتریش, ایرانیان اتریش, وین, قوانین اتریش, خدمات فارسی زبانان اتریش`,
        breadcrumbName: segment,
        categoryName: "خدمات عمومی",
        schemaType: "WebPage"
      };
    }
  }

  // Item 14: Guarantee FAQPage Schema for EVERY individual page tailored to its topic
  if (!item.faqs || item.faqs.length === 0) {
    const label = item.breadcrumbName || item.title.split("|")[0].trim();
    item.faqs = [
      {
        q: `مهم‌ترین نکات و شرایط قانونی بخش ${label} در اتریش در سال ۲۰۲۶ چیست؟`,
        a: `در سال ۲۰۲۶ بخش ${label} در اتریش مطابق آخرین اصلاحات حقوقی و اداری فدرال تنظیم شده و نیازمند رعایت پیش‌نیازهای قانونی، استانداردهای اداری و مدارک رسمی معتبر است.`
      },
      {
        q: `چگونه می‌توان به ابزارها، محاسبان و خدمات رایگان ${label} در اتریش‌نشین دسترسی داشت؟`,
        a: `تمامی خدمات، راهنماهای گام‌به‌گام، فایل‌های نمونه و شبیه‌سازهای مرتبط با ${label} به صورت رایگان در پورتال اتریش‌نشین برای تسهیل امور هموطنان در دسترس است.`
      }
    ];
  }

  // Item 2: Expand keywords with Persian spelling variants (نیم‌فاصله vs فاصله vs متصل و اصطلاحات عامیانه)
  item.keywords = expandKeywordsWithVariants(item.keywords);

  return item;
}
